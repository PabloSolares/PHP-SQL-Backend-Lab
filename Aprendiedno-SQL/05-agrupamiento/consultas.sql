# CONSULTAS DE AGRUPAMIENTO #
SELECT COUNT(titulo) AS 'NUMERO DE ENTRADAS', categoria_id FROM entradas GROUP BY categoria_id;

# CONSULATDA DE AGRUPACMINETO CON CONDICION #
SELECT COUNT(titulo) AS 'NUMERO DE ENTRADAS', categoria_id FROM entradas GROUP BY categoria_id HAVING COUNT(titulo) >= 4;


/*
AVG     SACAR LA MEDIA
COUNT   PERMITE CONTAR EL NUMERO DE ELEMENTOS
MAX     VALOR MAXIMO DEL GRUPO
MIN     VALOR MINIMO DEL GRUPO
SUM     SUMAR TODO EL CONTENIDO DEL GRUPO
*/

# MEDIA #
SELECT AVG(id) AS 'MEDIA DE ENTRADAS' FROM entradas;

# MAX #
SELECT MAX(id) AS 'USUARIO MAXIMO ID', titulo FROM entradas;

# MIN #
SELECT MIN(id) AS 'USUARIO MINIMO ID', titulo FROM entradas;

# SUM #
SELECT SUM(id) AS 'SUM ID', titulo FROM entradas;















